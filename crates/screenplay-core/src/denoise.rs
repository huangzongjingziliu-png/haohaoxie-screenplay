//! PDF / 导入去噪：页码、页眉、页脚、重复导出水印。
//!
//! 原则（说明书第 34 条）：不能永久直接删除原文。
//! 被过滤内容记录到 `ImportInfo.removed_noise`，原文保留在 `original_text`。

/// 中文断行恢复：把 PDF 抽取产生的硬换行接回
///
/// 但如果上一行是 Scene Heading 或 Character，则不能合并（说明书第 35 条）
pub fn repair_broken_lines(text: &str) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let mut out: Vec<String> = Vec::with_capacity(lines.len());

    for line in lines {
        let trimmed = line.trim_end();
        let is_empty = trimmed.trim().is_empty();

        // 空行直接保留为段落边界
        if is_empty {
            out.push(String::new());
            continue;
        }

        let can_merge = match out.last() {
            None => false,
            Some(prev) => {
                if prev.trim().is_empty() {
                    false
                } else {
                    // 上一行若是场景标题或人物名，不能合并
                    !ends_like_heading(prev) && !ends_like_speaker(prev)
                }
            }
        };

        // 中文行尾无终止标点 → 可能是被切断的句子
        let needs_join = can_merge && !ends_with_terminator(trimmed);

        if needs_join {
            if let Some(prev) = out.last_mut() {
                prev.push_str(trimmed.trim_start());
                continue;
            }
        }
        out.push(trimmed.to_string());
    }

    out.join("\n")
}

fn ends_with_terminator(s: &str) -> bool {
    s.trim_end()
        .chars()
        .last()
        .is_some_and(|c| "。！？…：；，、）】》”』.!?;:)]}".contains(c))
}

fn ends_like_heading(s: &str) -> bool {
    let t = s.trim();
    if t.is_empty() {
        return false;
    }
    // 中文顿号/中点结尾、含内外景前缀
    if t.starts_with("内") || t.starts_with("外") {
        return true;
    }
    let u = t.to_ascii_uppercase();
    u.starts_with("INT") || u.starts_with("EXT")
}

fn ends_like_speaker(s: &str) -> bool {
    let t = s.trim();
    // "剑客：" 或 "SWORDSMAN"
    if t.ends_with('：') || t.ends_with(':') {
        return true;
    }
    if t.contains('：') && t.chars().count() <= 12 {
        return true;
    }
    false
}

#[derive(Debug, Clone, Default)]
pub struct DenoiseResult {
    pub text: String,
    pub removed: Vec<String>,
}

/// 统计重复噪声：出现 >= max(3, 5%) 次的整行，且不像正文（不以句读标点结尾）
pub fn detect_repeated(lines: &[&str]) -> Vec<String> {
    use std::collections::HashMap;
    let mut freq: HashMap<&str, usize> = HashMap::new();
    for l in lines {
        let t = l.trim();
        if t.chars().count() < 2 {
            continue;
        }
        // 以句读标点结尾的行更像正文，不作为重复噪声
        if ends_with_terminator(t) {
            continue;
        }
        *freq.entry(t).or_insert(0) += 1;
    }
    let threshold = std::cmp::max(3, lines.len() / 20);
    let mut v: Vec<String> = freq
        .into_iter()
        .filter(|(_, c)| *c >= threshold)
        .map(|(t, _)| t.to_string())
        .collect();
    v.sort();
    v
}

pub fn is_page_number_line(s: &str) -> bool {
    let t = s.trim();
    if t.is_empty() {
        return false;
    }
    // 纯数字 / 数字+点
    let core = t.trim_end_matches(['.', '．', '、']);
    if !core.is_empty() && core.chars().all(|c| c.is_ascii_digit()) && core.len() <= 4 {
        return true;
    }
    if t.starts_with("第") && t.ends_with("页") {
        return true;
    }
    let u = t.to_ascii_lowercase();
    u.starts_with("page ") && u[5..].trim().chars().all(|c| c.is_ascii_digit())
}

/// 常见导出水印 / 页眉关键词
pub fn is_noise_keyword(s: &str) -> bool {
    let t = s.trim();
    if t.is_empty() {
        return false;
    }
    const PREFIXES: &[&str] = &[
        "由",
        "Generated by",
        "Exported from",
        "Exported",
        "Created with",
        "Scriptation",
        "WriterSolo",
        "Final Draft",
        "Fade In",
        "海马轻帆",
        "壹写作",
        "汤圆创作",
        "本页由",
        "本文由",
        "下载自",
        "导出自",
    ];
    if PREFIXES.iter().any(|p| t.starts_with(p)) {
        // "由XX导出/排版" 这类；或纯导出工具署名
        return true;
    }
    if t.starts_with("http://") || t.starts_with("https://") || t.starts_with("www.") {
        return true;
    }
    // 版权声明式页脚
    if t.contains("版权所有") && t.chars().count() < 60 {
        return true;
    }
    false
}

/// 对整篇文本去噪
pub fn denoise(text: &str) -> DenoiseResult {
    let lines: Vec<&str> = text.lines().collect();
    let repeated = detect_repeated(&lines);
    let mut removed: Vec<String> = Vec::new();
    let mut out: Vec<String> = Vec::with_capacity(lines.len());

    for line in lines {
        let t = line.trim();
        let drop = repeated.iter().any(|r| r == t)
            || is_page_number_line(line)
            || is_noise_keyword(line);
        if drop {
            if !t.is_empty() && !removed.iter().any(|r| r == t) {
                removed.push(t.to_string());
            }
            out.push(String::new());
        } else {
            out.push(line.to_string());
        }
    }

    // 折叠连续空行
    let mut cleaned = String::new();
    let mut blank = 0;
    for l in out {
        if l.trim().is_empty() {
            blank += 1;
            if blank > 1 {
                continue;
            }
            cleaned.push('\n');
        } else {
            blank = 0;
            cleaned.push_str(&l);
            cleaned.push('\n');
        }
    }

    DenoiseResult {
        text: cleaned.trim().to_string(),
        removed,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn d01_repeated_watermark_removed() {
        let mut s = String::new();
        for i in 0..40 {
            if i % 2 == 0 {
                s.push_str("由海马轻帆智能导出\n");
            } else {
                s.push_str("风从荒原吹来。\n");
            }
        }
        let r = denoise(&s);
        assert!(
            !r.text.contains("由海马轻帆智能导出"),
            "重复水印应被过滤"
        );
        assert!(r.removed.iter().any(|x| x.contains("海马轻帆")));
        // 正文保留
        assert!(r.text.contains("风从荒原吹来"));
    }

    #[test]
    fn d02_page_numbers_removed() {
        let r = denoise("12.\n\n正文内容。\n\n13.\n");
        assert!(!r.text.contains("12."));
        assert!(!r.text.contains("13."));
        assert!(r.text.contains("正文内容"));
    }

    #[test]
    fn d03_non_repeated_body_kept() {
        // 少于阈值次数的行不能被误删
        let mut s = String::new();
        for i in 0..30 {
            s.push_str(&format!("第{}行不同的内容，剑客走向城门。\n", i));
        }
        let r = denoise(&s);
        assert_eq!(r.text.lines().filter(|l| !l.trim().is_empty()).count(), 30);
    }

    #[test]
    fn repair_joins_chinese_broken_line() {
        let input = "我是一个爱做梦的人，曾梦见自己不止一次来边关。据\n说，世上只有两种男人会铁了心选择北上";
        let out = repair_broken_lines(input);
        assert_eq!(
            out.trim(),
            "我是一个爱做梦的人，曾梦见自己不止一次来边关。据说，世上只有两种男人会铁了心选择北上"
        );
    }

    #[test]
    fn repair_does_not_join_after_scene_heading() {
        let input = "外. 镇北堡城门 - 黄昏\n风从荒原吹来。";
        let out = repair_broken_lines(input);
        assert_eq!(out.lines().count(), 2);
    }

    #[test]
    fn repair_does_not_join_after_speaker() {
        let input = "老板娘：昨日\n去了买卖城。";
        let out = repair_broken_lines(input);
        assert_eq!(out.lines().count(), 2);
    }
}
